"""REANALYSIS.md from ``results_v3/reanalysis/reanalysis.json`` (no simulation).

Tables with one line of framing each; the summary report over v1 to v3
(roadmap report rules) draws on these numbers.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

NAMES = {
    "v1": "v1 score",
    "decoder-graph": "decoder-graph score",
    "lowest-summed-error": "lowest summed error",
    "qiskit-vf2": "Qiskit VF2Layout (v2 target)",
    "qiskit-default-l1": "Qiskit default, level 1",
    "qiskit-default-l2": "Qiskit default, level 2",
    "qiskit-default-l3": "Qiskit default, level 3",
    "mapomatic": "mapomatic",
    "fixed": "naive placement",
    "average": "all-placement average",
}
DEVICE = {"jakarta": "FakeJakarta", "hanoi": "FakeHanoi", "algiers": "FakeAlgiers"}
LABEL = {"A": "d=3 Z", "B": "d=3 X", "D5": "d=5", "D7": "d=7"}
V1_LABEL = {
    "A1": "d=3, 1 round",
    "A3": "d=3, 3 rounds",
    "A5": "d=3, 5 rounds",
    "B": "d=3 X",
    "C": "d=2",
    "D5": "d=5",
    "D7": "d=7",
}


def _minus(text: str) -> str:
    return text.replace("-", "−")


def _pct(i: dict[str, float]) -> str:
    e, lo, hi = (100 * i[k] for k in ("estimate", "low", "high"))
    return _minus(f"{e:+.1f}% [{lo:+.1f}%, {hi:+.1f}%]")


def _sci(x: float) -> str:
    if x == 0:
        return "0"
    return _minus(f"{x:.1e}".replace("e-0", "e-"))


def _p(x: float) -> str:
    if x >= 0.01:
        return f"{x:.2f}"
    if x < 1e-10:
        return "< 1e−10"
    return _sci(x)


def _case(row: dict[str, Any]) -> str:
    cid = row["case_id"]
    if not cid.startswith("v2-"):
        device, label, *rest = cid.split("-")
        return f"{DEVICE[device]} {V1_LABEL[label]}, {'-'.join(rest)}"
    return _v2_case(cid)


def _v2_case(cid: str) -> str:
    device, label = cid.split("-")[1:3]
    return f"{DEVICE[device]} {LABEL[label]}"


def _table(head: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _rate_interval(i: dict[str, float]) -> str:
    return f"{_sci(i['estimate'])} [{_sci(i['low'])}, {_sci(i['high'])}]"


def write_report(
    result: dict[str, Any],
    step6b: dict[str, Any],
    path: Path,
    mirror: dict[str, Any] | None = None,
) -> Path:
    prov = result["provenance"]
    lines: list[str] = []
    w = lines.append
    w("# Re-analysis of the v1 and v2 counts (roadmap Steps 6 and 6b)")
    w("")
    w(
        "Generated by `python -m nac_bench.reanalysis configs_v3/reanalysis.json` from the committed "
        "`results/runs` and `results_v2/runs` "
        f"(code commit `{str(prov['package_git_commit'])[:7]}`). No placement was simulated: every "
        "number comes from failure counts already committed. **Status: post hoc.** These rules and "
        "families were written after every v1 and v2 result had been seen, so this is a labelled "
        "re-analysis, not a pre-registered test."
    )
    w("")
    w(f"**Verdict rule**, used everywhere below: {result['verdict_rule']}.")
    w("")
    w(
        "Every row is development data except FakeAlgiers rows, which are held out. P_L is the logical "
        "error rate per shot. Changes are relative to the reference named in the row, with 95% "
        "intervals. The naive placement is the one REPORT.md and REPORT_V2.md call *fixed*: the "
        "first valid placement in lexicographic order."
    )
    w("")

    changed = result["changed_verdicts"]
    n1 = sum(1 for r in changed if r["version"] == "v1")
    n2 = sum(
        1
        for r in changed
        if r["version"] == "v2"
        and r["method"] in ("v1", "decoder-graph")
        and r["reference"] in ("fixed", "average", "lowest-summed-error", "qiskit-vf2")
    )
    w("## 1. Which verdicts change under the difference rule?")
    w("")
    w(
        f"{n1} v1 comparisons and {n2} of v2's own comparisons change. Each was called "
        "indistinguishable by the overlap rule although its difference interval excludes zero. Rows "
        "against the new baselines repeat a v2 row when that baseline chose the same placement."
    )
    w("")
    w(
        _table(
            ["Version", "Case", "Choice", "Reference", "Change [95% CI]", "Old", "New"],
            [
                [
                    r["version"],
                    _case(r),
                    NAMES[r["method"]],
                    NAMES[r["reference"]],
                    _pct(r["relative"]),
                    r["old_verdict"],
                    r["verdict"],
                ]
                for r in changed
            ],
        )
    )
    w("")

    w("## 2. Which headline comparisons survive Holm's correction?")
    w("")
    for name, fam in result["holm"].items():
        holds = sum(1 for m in fam["members"] if m["holds_after_holm"])
        nontie = sum(1 for m in fam["members"] if m["verdict"] != "tie")
        w(
            f"**{name}**: {fam['description']}. {fam['size']} comparisons at α = {fam['alpha']}; "
            f"{nontie} have a non-tie verdict and {holds} hold after Holm."
        )
        w("")
        w(
            _table(
                ["Case", "vs", "Change [95% CI]", "Verdict", "p", "Holm p", "Holds"],
                [
                    [
                        _case(m) + (" (held-out)" if m["role"] == "held-out" else ""),
                        NAMES[m["reference"]],
                        "same placement" if m["same_placement"] else _pct(m["relative"]),
                        m["verdict"],
                        _p(m["p_value"]),
                        _p(m["holm_p"]),
                        "yes" if m["holds_after_holm"] else "no",
                    ]
                    for m in fam["members"]
                ],
            )
        )
        w("")

    first = next(iter(step6b["cases"].values()))
    w("## 3. What do Qiskit's default transpile and mapomatic choose?")
    w("")
    w(
        "Both ran on the converted snapshot's published values: an IBM-shaped Target, and for mapomatic "
        "an adapter serving that Target as `properties()`. Qiskit "
        f"{step6b['qiskit_version']}, mapomatic {step6b['mapomatic_version']}, `seed_transpiler` = "
        f"{first['qiskit-default-l1']['seed_transpiler']}. *Pass* is the pass that produced the final "
        "layout, and *seeds* counts the distinct placements ten other transpiler seeds gave. mapomatic "
        "scores a placement and its mirror identically, so its pick between the two is arbitrary; "
        "*tied mean* is the mean P_L over its tied-best set."
    )
    w("")
    rows = []
    for cid, rec in step6b["cases"].items():
        row = [_v2_case(cid)]
        for level in (1, 2, 3):
            r = rec[f"qiskit-default-l{level}"]
            status = r["layout_pass"] if r["failure"] is None else r["failure"]
            row.append(f"{status}, seeds {r['seed_sweep_distinct_mappings']}")
        m = rec["mapomatic"]
        row.append(
            f"{len(m['tied_best'])} tied of {m['num_layouts']}"
            + ("" if m["failure"] is None else f", {m['failure']}")
        )
        row.append(_sci(result["mapomatic_tied_best_mean"][cid]))
        fake = rec.get("_fake_backend_target")
        if fake is None:
            row.append("not run")
        else:
            notes = []
            for level in (1, 2, 3):
                f = fake[f"qiskit-default-l{level}"]
                if f["mapping"] == rec[f"qiskit-default-l{level}"]["mapping"]:
                    continue
                if f["removed_couplers_used"]:
                    pairs = ", ".join(f"{a}–{b}" for a, b in f["removed_couplers_used"])
                    notes.append(f"L{level} uses removed coupler {pairs}")
                else:
                    notes.append(f"L{level} picks another placement")
            row.append("; ".join(notes) if notes else "same choices")
        rows.append(row)
    w(
        _table(
            [
                "Case",
                "Level 1",
                "Level 2",
                "Level 3",
                "mapomatic",
                "Tied mean P_L",
                "On the fake backend's own Target",
            ],
            rows,
        )
    )
    w("")
    w(
        "The last column is context. The fake backend's own Target still lists the couplers the "
        "conversion removed, with CX error 1.0 in one direction and a normal error in the other, so "
        "Qiskit can route a gate through one in its working direction. Those placements are outside "
        "the candidate set every method here chose from, so they have no counts."
    )
    w("")
    w("Each method's choice against the naive placement:")
    w("")
    methods = (
        "decoder-graph",
        "lowest-summed-error",
        "qiskit-vf2",
        "qiskit-default-l1",
        "qiskit-default-l2",
        "qiskit-default-l3",
        "mapomatic",
    )
    vs_fixed = {
        (r["case_id"], r["method"]): r
        for r in result["comparisons"]
        if r["version"] == "v2" and r["reference"] == "fixed"
    }
    rows = []
    for cid in step6b["cases"]:
        row = [_v2_case(cid), _sci(vs_fixed[(cid, "decoder-graph")]["reference_rate"]["estimate"])]
        for method in methods:
            r = vs_fixed.get((cid, method))
            if r is None:
                row.append("no SWAP-free choice")
            elif r["same_placement"]:
                row.append("naive placement")
            else:
                row.append(f"{_pct(r['relative'])} {r['verdict']}")
        rows.append(row)
    w(_table(["Case", "Naive P_L", *[NAMES[m] for m in methods]], rows))
    w("")

    w("## 4. How far is each choice from the best placement, without oracle bias?")
    w("")
    w(
        "The best placement is picked on two seeds and measured on the third, rotating through all "
        "three. *Bias* is how much lower the in-sample best (picked and measured on the same data) is "
        "than this cross-fitted best. Regret is each choice's P_L relative to the cross-fitted best on "
        "the same folds; *tie* means the choice is not separated from it."
    )
    w("")
    order = ("v1", "decoder-graph", "lowest-summed-error", "qiskit-default-l1", "mapomatic")
    rows = []
    for cid, fit in result["cross_fit"]["v2"].items():
        row = [
            _v2_case(cid),
            _sci(fit["in_sample_best"]),
            _sci(fit["best"]["estimate"]),
            _minus(f"{100 * fit['oracle_bias']:+.1f}%"),
        ]
        for m in order:
            r = fit["regret"].get(m)
            row.append("—" if r is None else f"{_pct(r['relative'])} {r['verdict']}")
        rows.append(row)
    w(
        _table(
            ["Case", "In-sample best", "Cross-fitted best", "Bias", *[NAMES[m] for m in order]],
            rows,
        )
    )
    w("")
    w("v1 headline cases (real converted noise), the v1 score's choice:")
    w("")
    rows = []
    for cid, fit in result["cross_fit"]["v1"].items():
        if not cid.endswith("-N2"):
            continue
        r = fit["regret"]["v1"]
        rows.append(
            [
                _case({"case_id": cid}),
                _sci(fit["in_sample_best"]),
                _sci(fit["best"]["estimate"]),
                _minus(f"{100 * fit['oracle_bias']:+.1f}%"),
                _minus(f"{100 * r['in_sample_relative']:+.1f}%"),
                f"{_pct(r['relative'])} {r['verdict']}",
            ]
        )
    w(
        _table(
            [
                "Case",
                "In-sample best",
                "Cross-fitted best",
                "Bias",
                "In-sample regret",
                "Cross-fitted regret",
            ],
            rows,
        )
    )
    w("")

    w("## 5. How much of the gain survives drift, in absolute terms?")
    w("")
    w(
        f"{result['m6_rule']}. Gain is P_L(naive) − P_L(choice), so a negative gain means the method's "
        "own choice is worse than the naive placement. Shown at δ = 0.5; every strength is in the JSON."
    )
    w("")
    rows = []
    for d in result["drift"]:
        if d["delta"] != 0.5:
            continue
        m6 = d["m6"]
        rows.append(
            [
                _v2_case(d["case_id"]),
                NAMES[d["method"]],
                _rate_interval(d["gain"]),
                _rate_interval(d["retained"]),
                "not stable"
                if m6 is None
                else _minus(f"{m6['estimate']:.2f} [{m6['low']:.2f}, {m6['high']:.2f}]"),
            ]
        )
    w(_table(["Case", "Method", "Gain, true model", "Gain kept at δ = 0.5", "M6"], rows))
    w("")

    w("## 6. Does the gain shrink with distance, in relative terms?")
    w("")
    w(
        "Error rates fall about 60× from d=3 to d=7, so absolute differences shrink even when the "
        "relative gain does not. Decoder-graph score, Z-basis circuits with 3 rounds:"
    )
    w("")
    pair = {
        (r["case_id"], r["reference"]): r
        for r in result["comparisons"]
        if r["version"] == "v2" and r["method"] == "decoder-graph"
    }
    rows = []
    for device in ("hanoi", "algiers"):
        for label in ("A", "D5", "D7"):
            cid = f"v2-{device}-{label}"
            row = [_v2_case(cid)]
            for ref in ("fixed", "lowest-summed-error", "qiskit-default-l1", "mapomatic"):
                r = pair.get((cid, ref))
                if r is None:
                    row.append("—")
                elif r["same_placement"]:
                    row.append("same placement")
                else:
                    row.append(_pct(r["relative"]))
            rows.append(row)
    w(
        _table(
            [
                "Case",
                "vs naive",
                "vs lowest summed error",
                "vs Qiskit default, level 1",
                "vs mapomatic",
            ],
            rows,
        )
    )
    w("")

    w("## 7. Does mapomatic's cost rank placements the way the simulation does?")
    w("")
    w("Spearman's ρ between mapomatic's cost and simulated P_L over every SWAP-free placement:")
    w("")
    w(
        _table(
            ["Case", "ρ"],
            [[_v2_case(c), _minus(f"{rho:.2f}")] for c, rho in result["mapomatic_m4"].items()],
        )
    )
    w("")

    if mirror is not None:
        w("## 8. Does a mirror pair's gap follow the gate order or the qubits?")
        w("")
        w(
            "The gate order. FakeHanoi d=7 placement "
            f"({', '.join(map(str, mirror['mapping']))}) and its mirror, each with the two CX layers in "
            "v2's order and swapped, on three fresh seeds. Swapping the layers on one placement gives "
            "its mirror's physical schedule, so the *same schedule* rows compare physically identical "
            "circuits; this checks the explanation and the pipeline, not hardware."
        )
        w("")
        w(
            _table(
                ["Comparison", "Change [95% CI]", "Verdict"],
                [
                    [name, _pct(c["relative"]), c["verdict"]]
                    for name, c in mirror["comparisons"].items()
                ],
            )
        )
        w("")
        w(
            "Command: `python -m nac_bench.mirror_check configs_v3/mirror_check.json` "
            f"({mirror['provenance']['wall_clock_seconds']:.0f} s on "
            f"{mirror['provenance']['machine']['workers']} workers)."
        )
        w("")

    m = prov["machine"]
    w("## Reproducibility")
    w("")
    w("```")
    w("python -m nac_bench.reanalysis configs_v3/reanalysis.json")
    w(f"config sha256  {prov['config_sha256']}")
    w(f"commit         {prov['package_git_commit']} (dirty: {prov['package_git_dirty']})")
    w("versions       " + ", ".join(f"{k} {v}" for k, v in prov["versions"].items()))
    w(
        f"machine        {m['cpu_model']}, {m['usable_cores']} cores, {m['memory_gib']} GiB, "
        f"{m['os']}, Python {m['python']}"
    )
    w("stage seconds  " + ", ".join(f"{k} {v:.1f}" for k, v in prov["stage_seconds"].items()))
    w("```")
    w("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def main() -> int:
    """Rewrite REANALYSIS.md from the committed JSON files, without recomputing."""

    root = Path(__file__).resolve().parent.parent
    out = root / "results_v3" / "reanalysis"
    result = json.loads((out / "reanalysis.json").read_text(encoding="utf-8"))
    step6b = json.loads((out / "baselines.json").read_text(encoding="utf-8"))
    mirror_path = root / "results_v3" / "mirror_check.json"
    mirror = json.loads(mirror_path.read_text(encoding="utf-8")) if mirror_path.exists() else None
    print(f"wrote {write_report(result, step6b, out / 'REANALYSIS.md', mirror)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


__all__ = ["NAMES", "write_report"]
